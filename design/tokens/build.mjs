/* Generates tokens.css (custom properties + type classes) and tokens.json from source.mjs. */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { color, seriesNames, fontFamily, type, space, radius, size, stroke, layout, z, timing, glass, glassAdapt, motion } from "./source.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const vars = (obj) => Object.entries(obj).map(([k, v]) => `  --${k}: ${v};`).join("\n");

const shared = {
  ...Object.fromEntries(Object.entries(fontFamily).map(([k, v]) => [`font-${k}`, v])),
  ...Object.fromEntries(space.map((s) => [`space-${s}`, `${s}px`])),
  ...Object.fromEntries(Object.entries(radius).map(([k, v]) => [`radius-${k}`, `${v}px`])),
  ...Object.fromEntries(Object.entries(size).map(([k, v]) => [`size-${k}`, `${v}px`])),
  ...Object.fromEntries(Object.entries(stroke).map(([k, v]) => [`stroke-${k}`, `${v}px`])),
  ...Object.fromEntries(Object.entries(layout).map(([k, v]) => [`layout-${k}`, v < 1 ? v : `${v}px`])),
  ...Object.fromEntries(Object.entries(z).map(([k, v]) => [`z-${k}`, v])),
  ...Object.fromEntries(Object.entries(timing).map(([k, v]) => [`time-${k}`, `${v}ms`])),
  ...Object.fromEntries(Object.entries(glass).map(([k, v]) => [`glass-${k.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())}`, v])),
  ...Object.fromEntries(Object.entries(motion).flatMap(([k, v]) => [[`ease-${k}`, v.easing], [`dur-${k}`, `${v.duration}ms`]])),
};

const typeCss = Object.entries(type).map(([k, [fam, w, sz, lh, ls, tt, st]]) =>
  `.t-${k} { font-family: var(--font-${fam}); font-weight: ${w}; font-size: ${sz}px; line-height: ${lh}px; letter-spacing: ${ls}em;${tt !== "none" ? ` text-transform: ${tt};` : ""}${st !== "normal" ? ` font-style: ${st};` : ""}${k.startsWith("numeric") ? " font-variant-numeric: tabular-nums;" : ""} }`).join("\n");

const css = `/* GENERATED by design/tokens/build.mjs from source.mjs. Do not edit by hand. */
@import url("https://fonts.googleapis.com/css2?family=Inter:wght@300..800&family=Instrument+Serif:ital@0;1&family=Geist+Mono:wght@400;500&display=swap");

:root {
${vars(shared)}
}

/* Dark is the default; light applies with data-theme="light" or the OS setting. */
:root, :root[data-theme="dark"] {
  color-scheme: dark;
${vars(color.dark)}
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
    color-scheme: light;
${vars(color.light).replace(/^/gm, "  ")}
  }
}
:root[data-theme="light"] {
  color-scheme: light;
${vars(color.light)}
}

/* Adaptive glass: set by lib/glass.js from what is underneath. */
.lg[data-under="light"] {
${vars(glassAdapt.light)}
}
.lg[data-under="dark"] {
${vars(glassAdapt.dark)}
}

${typeCss}
`;
writeFileSync(join(here, "tokens.css"), css);

const json = {
  $description: "viz design tokens. Generated from source.mjs; same names as tokens.css custom properties.",
  color: { dark: color.dark, light: color.light, seriesNames },
  font: fontFamily,
  type: Object.fromEntries(Object.entries(type).map(([k, [family, weight, size, lineHeight, letterSpacing, transform, style, use]]) => [k, { family, weight, size, lineHeight, letterSpacing, transform, style, use }])),
  space, radius, size, stroke, layout, z, timing, glass, glassAdapt,
  motion,
};
writeFileSync(join(here, "tokens.json"), JSON.stringify(json, null, 2) + "\n");
console.log("wrote tokens.css and tokens.json");
